export const renderFlclashOverride = (providers, releaseBaseUrl, proxyGroup) => {
  const automaticGroup = "⚡ 自动选择";
  const aiGroup = "🤖 AI";
  const microsoftGroup = "🪟 Microsoft";
  const streamingGroup = "📺 流媒体";
  const appleGroup = "🍎 Apple";
  const googleGroup = "🔍 Google";
  const socialGroup = "💬 社交媒体";
  const unmatchedGroup = "🐟 漏网之鱼";
  const testUrl = "https://www.gstatic.com/generate_204";
  const japanNodeFilter =
    "(?i)(?:JP|JPN|Japan|日本|Tokyo|東京|Osaka|大阪|🇯🇵)";

  const domainSelectGroup = (name) => ({
    name,
    type: "select",
    proxies: [automaticGroup, "DIRECT"],
    "include-all": true,
  });

  const groups = [
    { name: proxyGroup, type: "select", "include-all": true },
    {
      name: automaticGroup,
      type: "url-test",
      url: testUrl,
      interval: 300,
      tolerance: 50,
      "include-all": true,
    },
    {
      name: aiGroup,
      type: "fallback",
      url: testUrl,
      interval: 300,
      "include-all": true,
      filter: japanNodeFilter,
      "empty-fallback": "REJECT",
    },
    domainSelectGroup(microsoftGroup),
    domainSelectGroup(streamingGroup),
    domainSelectGroup(appleGroup),
    domainSelectGroup(googleGroup),
    domainSelectGroup(socialGroup),
    {
      name: unmatchedGroup,
      type: "select",
      proxies: [automaticGroup, "DIRECT"],
      "include-all": true,
    },
  ];

  const ruleProviders = Object.fromEntries(
    providers.map((provider) => [
      provider.name,
      {
        type: "http",
        behavior: "classical",
        format: "yaml",
        interval: 86400,
        path: `./rules/${provider.name}.yaml`,
        url: `${releaseBaseUrl}/rules/${provider.name}.yaml`,
        proxy: automaticGroup,
      },
    ])
  );
  const generatedRules = [
    ...providers.map((provider) => {
      const noResolve = provider.noResolve ? ",no-resolve" : "";
      return `RULE-SET,${provider.name},${provider.target}${noResolve}`;
    }),
    `MATCH,${unmatchedGroup}`,
  ];
  const generatedGroupNames = groups.map((group) => group.name);

  return [
    "// Generated by scripts/build.mjs; do not edit.",
    "function main(config) {",
    `  const generatedGroups = ${JSON.stringify(groups)};`,
    `  const generatedGroupNames = new Set(${JSON.stringify(generatedGroupNames)});`,
    `  const generatedRuleProviders = ${JSON.stringify(ruleProviders)};`,
    `  const generatedRules = ${JSON.stringify(generatedRules)};`,
    "",
    '  config["proxy-groups"] = (Array.isArray(config["proxy-groups"]) ? config["proxy-groups"] : []).filter(',
    "    (group) => !group?.name || !generatedGroupNames.has(group.name)",
    "  );",
    '  config["proxy-groups"].push(...generatedGroups);',
    "",
    '  const existingRuleProviders = config["rule-providers"];',
    '  config["rule-providers"] = {',
    '    ...(existingRuleProviders && typeof existingRuleProviders === "object" && !Array.isArray(existingRuleProviders)',
    '      ? existingRuleProviders',
    "      : {}),",
    "    ...generatedRuleProviders,",
    "  };",
    "",
    "  config.rules = generatedRules;",
    "  return config;",
    "}",
    "",
  ].join("\n");
};
