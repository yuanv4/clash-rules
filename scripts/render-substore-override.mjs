/**
 * Render the sub-store override script for the DS420 sub-store service.
 *
 * The output is a standalone `async function main(config = {}) { ... }` JS
 * file consumed by sub-store's mihomoConfig "Script Operator" (mode=link).
 *
 * Because this script runs inside sub-store (not inside mihomo), it cannot
 * use runtime `include-all` + `filter` and must build STATIC proxy lists
 * for each group from the parsed nodes.
 *
 * The Tailscale group and routing rules are always present. The dedicated
 * `tailscale` file reads a per-request identity from `$options.tailscale`;
 * legacy files whose names contain "tailscale" keep reading the local
 * `tailscale-secret` artifact for backward compatibility.
 */
export const renderSubstoreOverride = (providers, releaseBaseUrl, proxyGroup) => {
  const domesticGroup = "🇨🇳 国内服务";
  const foreignAiGroup = "🤖 国际 AI";
  const developerGroup = "🧑‍💻 开发服务";
  const foreignGroup = "🌐 国外服务";
  const streamingGroup = "🎬 流媒体服务";
  const adBlockGroup = "🛑 广告过滤";
  const fallbackGroup = "🐟 漏网之鱼";
  const automaticGroup = proxyGroup;
  const taiwanFallbackGroup = "🛟 故障转移(台湾)";
  const taiwanNodePattern = String.raw`(?:🇹🇼|\bTW(?=\b|\d)|\bTPE(?=\b|\d)|Taiwan|Taipei|台湾|台灣|台北)`;
  const tailscaleGroup = "Tailscale";
  const testUrl = "https://cp.cloudflare.com/generate_204";
  const hongKongNodePattern = String.raw`(?:🇭🇰|\bHKG?(?=\b|\d)|Hong\s*Kong|香港|港)`;

  const ruleProviders = Object.fromEntries(
    providers.map((provider) => [
      provider.name,
      {
        type: "http",
        behavior: provider.behavior ?? "classical",
        format: provider.behavior === "domain" ? "text" : "yaml",
        interval: 86400,
        url: `${releaseBaseUrl}/rules/${provider.name}.${provider.behavior === "domain" ? "txt" : "yaml"}`,
      },
    ]),
  );
  const rules = providers.map((provider) => {
    const noResolve = provider.noResolve ? ",no-resolve" : "";
    return `RULE-SET,${provider.name},${provider.target}${noResolve}`;
  });
  rules.push(`MATCH,${fallbackGroup}`);

  const businessGroups = [
    tailscaleGroup,
    adBlockGroup,
    domesticGroup,
    foreignGroup,
    foreignAiGroup,
    developerGroup,
    streamingGroup,
    fallbackGroup,
  ];
  const businessGroupSet = new Set(businessGroups);
  const providerGroupOrder = [];
  for (const provider of providers) {
    if (
      businessGroupSet.has(provider.target) &&
      provider.target !== tailscaleGroup &&
      provider.target !== fallbackGroup &&
      !providerGroupOrder.includes(provider.target)
    ) {
      providerGroupOrder.push(provider.target);
    }
  }
  const groupOrder = [
    tailscaleGroup,
    ...providerGroupOrder,
    ...businessGroups.filter(
      (name) => name !== tailscaleGroup && name !== fallbackGroup && !providerGroupOrder.includes(name),
    ),
    fallbackGroup,
    automaticGroup,
    taiwanFallbackGroup,
  ];

  const tailscaleRules = [
    "IP-CIDR,100.64.0.0/10,Tailscale,no-resolve",
    "IP-CIDR,100.100.100.100/32,Tailscale,no-resolve",
    "DOMAIN-SUFFIX,ts.net,Tailscale",
  ];

  return [
    "// Generated by scripts/build.mjs; do not edit.",
    "// Consumed by the DS420 sub-store mihomoConfig override (Script Operator, mode=link).",
    "async function main(config = {}) {",
    "  const fileName = ($file && $file.name) || '';",
    "  const runtimeOptions = typeof $options === 'undefined' ? undefined : $options;",
    "  const dynamicTailscale = fileName === 'tailscale';",
    "  const tailscaleOption = dynamicTailscale && runtimeOptions ? runtimeOptions.tailscale : undefined;",
    "  const withTailscale = dynamicTailscale ? tailscaleOption != null && tailscaleOption !== '' : fileName.indexOf('tailscale') !== -1;",
    "",
    "  const names = config.proxies.map((p) => p.name);",
    "  if (!names.length) throw new Error('Subscription has no proxies');",
    `  const hongKongPattern = new RegExp(${JSON.stringify(hongKongNodePattern)}, 'iu');`,
    "  const hongKongNames = names.filter((name) => hongKongPattern.test(name));",
    "  if (!hongKongNames.length) throw new Error('Subscription has no Hong Kong proxies');",
    `  const taiwanPattern = new RegExp(${JSON.stringify(taiwanNodePattern)}, 'iu');`,
    "  const taiwanNames = names.filter((name) => taiwanPattern.test(name));",
    "  const tailscaleProxies = withTailscale ? ['TAILSCALE', 'DIRECT'] : ['DIRECT'];",
    "  const proxyGroups = [",
    `    { name: '${automaticGroup}', type: 'url-test', url: '${testUrl}', interval: 300, tolerance: 50, proxies: hongKongNames },`,
    `    { name: '${taiwanFallbackGroup}', type: 'fallback', url: '${testUrl}', interval: 300, proxies: taiwanNames.length ? taiwanNames : ['REJECT'] },`,
    `    { name: '${foreignGroup}', type: 'select', proxies: ['DIRECT', '${automaticGroup}', '${taiwanFallbackGroup}'], 'default-selected': '${automaticGroup}' },`,
    `    { name: '${fallbackGroup}', type: 'select', proxies: ['DIRECT', '${automaticGroup}', '${taiwanFallbackGroup}'], 'default-selected': 'DIRECT' },`,
    `    { name: '${tailscaleGroup}', type: 'select', proxies: tailscaleProxies, 'default-selected': withTailscale ? 'TAILSCALE' : 'DIRECT' },`,
    `    { name: '${domesticGroup}', type: 'select', proxies: ['DIRECT', '${automaticGroup}', '${taiwanFallbackGroup}'], 'default-selected': 'DIRECT' },`,
    `    { name: '${foreignAiGroup}', type: 'select', proxies: ['DIRECT', '${automaticGroup}', '${taiwanFallbackGroup}'], 'default-selected': '${taiwanFallbackGroup}' },`,
    `    { name: '${developerGroup}', type: 'select', proxies: ['DIRECT', '${automaticGroup}', '${taiwanFallbackGroup}'], 'default-selected': '${taiwanFallbackGroup}' },`,
    `    { name: '${streamingGroup}', type: 'select', proxies: ['DIRECT', '${automaticGroup}', '${taiwanFallbackGroup}'], 'default-selected': '${automaticGroup}' },`,
    `    { name: '${adBlockGroup}', type: 'select', proxies: ['REJECT', 'DIRECT'], 'default-selected': 'REJECT' }`,
    "  ];",
    `  const groupOrder = ${JSON.stringify(groupOrder)};`,
    "  config['proxy-groups'] = groupOrder.map((name) => proxyGroups.find((group) => group.name === name));",
    "",
    "  config.mode = 'Rule';",
    "  config['log-level'] = 'info';",
    `  config['rule-providers'] = ${JSON.stringify(ruleProviders)};`,
    `  config.rules = ${JSON.stringify([...tailscaleRules, ...rules])};`,
    "",
    "  if (withTailscale) {",
    "    let secret;",
    "    if (dynamicTailscale) {",
    "      try {",
    "        secret = typeof tailscaleOption === 'string' ? JSON.parse(tailscaleOption) : tailscaleOption;",
    "      } catch {",
    "        throw new Error('Invalid $options.tailscale JSON');",
    "      }",
    "    } else {",
    "      secret = JSON.parse(await produceArtifact({ type: 'file', name: 'tailscale-secret' }));",
    "    }",
    "    if (!secret || typeof secret !== 'object' || Array.isArray(secret)) throw new Error('Invalid Tailscale options');",
    "    if (!secret.hostname || !secret['auth-key'] || !secret['state-dir']) throw new Error('Tailscale options require hostname, auth-key, and state-dir');",
    "    config.proxies = config.proxies.filter((p) => !(p && p.name === 'TAILSCALE'));",
    "    config.proxies.unshift({",
    "      name: 'TAILSCALE', type: 'tailscale',",
    "      hostname: secret.hostname,",
    "      'auth-key': secret['auth-key'],",
    "      'control-url': secret['control-url'],",
    "      'state-dir': secret['state-dir'],",
    "      ephemeral: !!secret.ephemeral,",
    "      udp: secret.udp !== false,",
    "      'accept-routes': secret['accept-routes'] !== false,",
    "      'ip-version': secret['ip-version'] || 'ipv4-prefer',",
    "    });",
    "  }",
    "",
    "  return config;",
    "}",
    "",
  ].join("\n");
};
