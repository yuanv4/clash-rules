/**
 * Render the sub-store override script for the DS420 sub-store service.
 *
 * The output is a standalone `async function main(config = {}) { ... }` JS
 * file consumed by sub-store's mihomoConfig "Script Operator" (mode=link).
 *
 * Because this script runs inside sub-store (not inside mihomo), it cannot
 * use runtime `include-all` + `filter` and must build STATIC proxy lists
 * for each group from the parsed nodes.
 *
 * The Tailscale group is always present; its node and routing rules are
 * enabled when the subscription name contains "tailscale".
 *
 * The Tailscale auth-key stays in a local sub-store file and is referenced by
 * name via `produceArtifact`; nothing secret is embedded.
 */
export const renderSubstoreOverride = (providers, releaseBaseUrl, proxyGroup) => {
  const domesticAiGroup = "🤖 国内 AI";
  const foreignAiGroup = "🤖 国际 AI";
  const googleGroup = "🌐 Google";
  const serviceGroups = ["🎬 Netflix", "🎬 DisneyPlus", "📲 电报信息", "💨 Steam商店", "Ⓜ️ 微软服务", "🍎 苹果服务", "🌍 媒体服务"];
  const adBlockGroup = "🛑 广告过滤";
  const fallbackGroup = "🐟 漏网之鱼";
  const automaticGroup = "♻️ 自动选择";
  const tailscaleGroup = "Tailscale";
  const testUrl = "https://cp.cloudflare.com/generate_204";
  const eastAsiaNodePattern = String.raw`(?:🇭🇰|🇲🇴|🇹🇼|🇯🇵|🇰🇷|🇨🇳|🇲🇳|HK|HKG|Hong\s*Kong|香港|港|\bMO\b|Macau|Macao|澳门|澳門|TW|TPE|Taiwan|Taipei|台湾|台灣|台北|JP|TYO|NRT|HND|KIX|OSA|Japan|Tokyo|Osaka|日本|东京|東京|大阪|KR|KOR|SEL|ICN|GMP|PUS|Korea|Seoul|韩国|韓國|首尔|首爾|CN|China|中国|中國|大陆|大陸|北京|上海|广州|深圳|Mongolia|蒙古|乌兰巴托|烏蘭巴托)`;

  const ruleProviders = Object.fromEntries(
    providers.map((provider) => [
      provider.name,
      {
        type: "http",
        behavior: "classical",
        format: "yaml",
        interval: 86400,
        url: `${releaseBaseUrl}/rules/${provider.name}.yaml`,
      },
    ]),
  );
  const rules = providers.map((provider) => {
    const noResolve = provider.noResolve ? ",no-resolve" : "";
    return `RULE-SET,${provider.name},${provider.target}${noResolve}`;
  });
  rules.push(`MATCH,${fallbackGroup}`);

  const tailscaleRules = [
    "IP-CIDR,100.64.0.0/10,Tailscale,no-resolve",
    "IP-CIDR,100.100.100.100/32,Tailscale,no-resolve",
    "DOMAIN-SUFFIX,ts.net,Tailscale",
  ];

  return [
    "// Generated by scripts/build.mjs; do not edit.",
    "// Consumed by the DS420 sub-store mihomoConfig override (Script Operator, mode=link).",
    "async function main(config = {}) {",
    "  const withTailscale = ($file && ($file.name || '').indexOf('tailscale') !== -1);",
    "",
    "  const names = config.proxies.map((p) => p.name);",
    "  if (!names.length) throw new Error('Subscription has no proxies');",
    `  const eastAsiaPattern = new RegExp(${JSON.stringify(eastAsiaNodePattern)}, 'i');`,
    "  const eastAsiaNames = names.filter((name) => eastAsiaPattern.test(name));",
    "  if (!eastAsiaNames.length) throw new Error('Subscription has no East Asia proxies');",
    "  const tailscaleProxies = withTailscale ? ['TAILSCALE', 'DIRECT'] : ['DIRECT'];",
    "  config['proxy-groups'] = [",
    `    { name: '${proxyGroup}', type: 'select', proxies: eastAsiaNames, 'default-selected': eastAsiaNames[0] },`,
    `    { name: '${automaticGroup}', type: 'url-test', url: '${testUrl}', interval: 300, tolerance: 50, proxies: eastAsiaNames },`,
    `    { name: '${fallbackGroup}', type: 'select', proxies: ['DIRECT', '${proxyGroup}', '${automaticGroup}'], 'default-selected': '${proxyGroup}' },`,
    `    { name: '${tailscaleGroup}', type: 'select', proxies: tailscaleProxies, 'default-selected': withTailscale ? 'TAILSCALE' : 'DIRECT' },`,
    `    { name: '${domesticAiGroup}', type: 'select', proxies: ['DIRECT', '${proxyGroup}', '${automaticGroup}'], 'default-selected': 'DIRECT' },`,
    `    { name: '${foreignAiGroup}', type: 'select', proxies: ['DIRECT', '${proxyGroup}', '${automaticGroup}'], 'default-selected': 'DIRECT' },`,
    `    { name: '${googleGroup}', type: 'select', proxies: ['DIRECT', '${proxyGroup}', '${automaticGroup}'], 'default-selected': 'DIRECT' },`,
    `    ...${JSON.stringify(serviceGroups)}.map((name) => ({ name, type: 'select', proxies: ['DIRECT', '${proxyGroup}', '${automaticGroup}'], 'default-selected': 'DIRECT' })),`,
    `    { name: '${adBlockGroup}', type: 'select', proxies: ['REJECT', 'DIRECT'], 'default-selected': 'REJECT' },`,
    "  ];",
    "",
    "  config.mode = 'Rule';",
    "  config['log-level'] = 'info';",
    `  config['rule-providers'] = ${JSON.stringify(ruleProviders)};`,
    `  config.rules = ${JSON.stringify(rules)};`,
    "",
    "  if (withTailscale) {",
    "    const secret = JSON.parse(await produceArtifact({ type: 'file', name: 'tailscale-secret' }));",
    "    config.proxies = config.proxies.filter((p) => !(p && p.name === 'TAILSCALE'));",
    "    config.proxies.unshift({",
    "      name: 'TAILSCALE', type: 'tailscale',",
    "      hostname: secret.hostname,",
    "      'auth-key': secret['auth-key'],",
    "      'control-url': secret['control-url'],",
    "      'state-dir': secret['state-dir'],",
    "      ephemeral: !!secret.ephemeral,",
    "      udp: secret.udp !== false,",
    "      'accept-routes': secret['accept-routes'] !== false,",
    "      'ip-version': secret['ip-version'] || 'ipv4-prefer',",
    "    });",
    `    config.rules = ${JSON.stringify(tailscaleRules)}.concat(config.rules);`,
    "  }",
    "",
    "  return config;",
    "}",
    "",
  ].join("\n");
};
